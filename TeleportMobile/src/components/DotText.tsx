interface DotTextProps {
    text: string;
    size?: number;
    color?: string;
    style?: any;
}

const DotText: React.FC<DotTextProps> = ({
    text,
    size = 6,
    color = '#ffffff',
    style,
}) => {
    const chars = text.toLowerCase().split('');
    const dotRadius = size / 2 - 0.5;
    const charWidth = size * 5 + size * 2; // 5 dots + 2 gap
    const charHeight = size * 7;
    const totalWidth = chars.length * charWidth;

    return (
        <View style={[styles.container, style]}>
            <Svg width={totalWidth} height={charHeight}>
                {chars.map((char, charIndex) => {
                    const pattern = CHAR_PATTERNS[char] || CHAR_PATTERNS[' '];
                    const offsetX = charIndex * charWidth;

                    return pattern.map((row, rowIndex) =>
                        row.map((dot, colIndex) => {
                            if (dot === 0) return null;
                            return (
                                <Circle
                                    key={`${charIndex}-${rowIndex}-${colIndex}`}
                                    cx={offsetX + colIndex * size + size / 2}
                                    cy={rowIndex * size + size / 2}
                                    r={dotRadius}
                                    fill={color}
                                />
                            );
                        })
                    );
                })}
            </Svg>
        </View>
    );
};

const styles = StyleSheet.create({
    container: {
        alignItems: 'flex-start',
    },
});

export default DotText;
